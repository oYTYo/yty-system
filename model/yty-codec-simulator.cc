EncodingParams YtyCodecSimulator::FindParams(double target_bitrate_kbps)
{
    // 复现 python 脚本中的优先级逻辑:
    // 优先级1: 帧率 (从高到低)
    for (int fr : m_frameRates) {
        // 优先级2: 分辨率 (从高到低)
        for (const auto& res : m_resolutions) {
            
            double best_bitrate = -1.0;
            const CodecDataEntry* best_match = nullptr;

            // 筛选出当前(fr, res)组合下所有低于目标码率的配置
            for (const auto& entry : m_codecDb) {
                if (entry.width == res.first && entry.height == res.second && entry.frameRate == fr && entry.avgBitrate_kbps <= target_bitrate_kbps) {
                    // 在这些配置中，选择码率最高的那个（即CRF最低，画质最好）
                    if (entry.avgBitrate_kbps > best_bitrate) {
                        best_bitrate = entry.avgBitrate_kbps;
                        best_match = &entry;
                    }
                }
            }

            if (best_match) {
                // 因为我们是从最佳配置(高帧率、高分辨率)开始往下找，所以第一个找到的就是最终答案
                EncodingParams params;
                params.resolution = best_match->resolution;
                params.crf = best_match->crf;
                params.frame_rate = best_match->frameRate;
                params.actual_bitrate_kbps = best_match->avgBitrate_kbps;
                params.found = true;
                return params;
            }
        }
    }

    // 如果遍历完所有组合都找不到，说明目标码率极低，返回全局最低配置
    const CodecDataEntry* lowest_config = nullptr;
    double min_bitrate = 1e9;
    for (const auto& entry : m_codecDb) {
        if (entry.avgBitrate_kbps < min_bitrate) {
            min_bitrate = entry.avgBitrate_kbps;
            lowest_config = &entry;
        }
    }
    
    if (lowest_config) {
        EncodingParams params;
        params.resolution = lowest_config->resolution;
        params.crf = lowest_config->crf;
        params.frame_rate = lowest_config->frameRate;
        params.actual_bitrate_kbps = lowest_config->avgBitrate_kbps;
        params.found = true;
        NS_LOG_INFO("Target bitrate " << target_bitrate_kbps << "kbps is too low. Using minimum available config.");
        return params;
    }
    
    // 如果数据库为空，返回未找到
    return EncodingParams();
}


